-- “Identifiquei 7 matrículas ativas de 2026 com id_escola = 60, 
--porém esse ID não existe na tabela de escolas. 
--Isso gera uma inconsistência de relacionamento e pode impactar os indicadores por unidade. 
--Precisamos validar a origem desses registros e o correto vínculo escolar.”

SELECT
    e.nome_escola,
    COUNT(DISTINCT m.id_aluno) AS qtd_alunos_ativos
FROM matriculas m
LEFT JOIN escolas e
    ON m.id_escola = e.id_escola
WHERE m.ano_letivo = 2026
  AND m.status = 'Ativa'
GROUP BY e.nome_escola
ORDER BY qtd_alunos_ativos DESC;


-- Quantidade de alunos ativos em 2026 por escola.
-- Considera apenas matrículas associadas a escolas válidas
-- e contabiliza alunos distintos por unidade.

SELECT
    e.nome_escola,
    COUNT(DISTINCT m.id_aluno) AS qtd_alunos_ativos
FROM matriculas m
INNER JOIN escolas e
    ON m.id_escola = e.id_escola
WHERE m.ano_letivo = 2026
  AND m.status = 'Ativa'
GROUP BY e.nome_escola
ORDER BY qtd_alunos_ativos DESC;



